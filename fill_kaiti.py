def set_cell_text(cell, text):
    """保留原有格式，替换单元格内首个文字"""
    ps = cell.paragraphs
    if not ps:
        return
    p = ps[0]
    if p.runs:
        p.runs[0].text = text
        for r in list(p.runs)[1:]:
            r._r.getparent().remove(r._r)
    else:
        p.add_run(text)


def make_para(donor, text):
    """以 donor 段落为模板生成新段落"""
    new = copy.deepcopy(donor)
    runs = new.findall(qn('w:r'))
    for r in runs[1:]:
        new.remove(r)
    if runs:
        r0 = runs[0]
        for child in list(r0):
            if child.tag in (qn('w:t'), qn('w:br'), qn('w:tab')):
                r0.remove(child)
        tnode = OxmlElement('w:t')
        tnode.set(qn('xml:space'), 'preserve')
        tnode.text = text
        r0.append(tnode)
    return new


